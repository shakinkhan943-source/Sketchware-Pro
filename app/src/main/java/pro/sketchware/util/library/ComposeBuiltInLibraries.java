package pro.sketchware.util.library;

import android.util.Log;

import com.google.gson.Gson;
import com.google.gson.annotations.SerializedName;

import java.io.File;
import java.io.FileNotFoundException;
import java.io.IOException;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.Reader;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

import pro.sketchware.SketchApplication;
import pro.sketchware.util.io.EncryptedFileUtil;
import pro.sketchware.util.io.ZipUtil;

/**
 * Separate built-in asset store for Jetpack Compose.
 *
 * Compose is deliberately not registered in {@link BuiltInLibraries}. Its Maven
 * artifacts, pre-dexed files, resources and ProGuard rules live in a dedicated
 * compose-libs.zip generated by GitHub Actions.
 */
public final class ComposeBuiltInLibraries {

    private static final String TAG = "ComposeBuiltInLibraries";
    public static final String ZIP_ASSET = "libs/compose-libs.zip";
    public static final String MANIFEST_ASSET = "libs/compose-libraries.json";

    public static final File ROOT = new File(BuiltInLibraries.EXTRACTED_COMPILE_ASSETS_PATH, "compose");
    private static final File LIBRARIES_ROOT = new File(ROOT, "libraries");
    private static final File DEX_ROOT = new File(ROOT, "dex");
    private static final File MANIFEST_FILE = new File(ROOT, "manifest.json");

    private static ComposeManifest cachedManifest;

    private ComposeBuiltInLibraries() {
    }

    public static synchronized void ensureExtracted() {
        File archive = new File(BuiltInLibraries.EXTRACTED_COMPILE_ASSETS_PATH, "compose-libs.zip");
        try {
            if (!BuiltInLibraries.EXTRACTED_COMPILE_ASSETS_PATH.exists()
                    && !BuiltInLibraries.EXTRACTED_COMPILE_ASSETS_PATH.mkdirs()) {
                throw new IOException("Failed to create built-in library directory");
            }

            EncryptedFileUtil fileUtil = new EncryptedFileUtil(false);
            boolean changed = ProjectAssetComparator.hasAssetChanged(ZIP_ASSET, archive);
            if (changed || !MANIFEST_FILE.exists()) {
                fileUtil.deleteDirectoryByPath(ROOT.getAbsolutePath());
                if (!ROOT.mkdirs()) {
                    throw new IOException("Failed to create Compose asset directory: " + ROOT);
                }
                new ZipUtil().extractZipFile(archive.getAbsolutePath(), ROOT.getAbsolutePath());
                cachedManifest = null;
            }
        } catch (FileNotFoundException e) {
            throw new IllegalStateException("Jetpack Compose built-in bundle is missing: " + ZIP_ASSET, e);
        } catch (IOException e) {
            throw new IllegalStateException("Failed to extract Jetpack Compose built-in bundle", e);
        }
    }

    public static synchronized ComposeManifest getManifest() {
        ensureExtracted();
        if (cachedManifest == null) {
            try (Reader reader = new InputStreamReader(new java.io.FileInputStream(MANIFEST_FILE), StandardCharsets.UTF_8)) {
                cachedManifest = new Gson().fromJson(reader, ComposeManifest.class);
            } catch (IOException | RuntimeException e) {
                throw new IllegalStateException("Failed to read Compose dependency manifest", e);
            }
        }
        if (cachedManifest == null || cachedManifest.features == null) {
            throw new IllegalStateException("Invalid Compose dependency manifest");
        }
        return cachedManifest;
    }

    public static List<ComposeFeature> getFeatures() {
        return getManifest().features;
    }

    /**
     * Returns {@code true} when the built-in Compose bundle asset is present in the APK.
     * The bundle is generated by CI ({@code scripts/compose/build_compose_bundle.py}) and
     * may legitimately be absent on a build made before that workflow has run, so callers
     * that show optional UI (e.g. {@code ComposeLibraryActivity}) should check this first
     * instead of letting {@link #getManifest()} throw.
     */
    public static boolean isBundleAvailable() {
        try (InputStream probe = SketchApplication.getAppContext().getAssets().open(ZIP_ASSET)) {
            return true;
        } catch (IOException e) {
            return false;
        }
    }

    public static List<ComposeArtifact> getSelectedArtifacts(List<String> optionalFeatureIds) {
        ComposeManifest manifest = getManifest();
        Set<String> selectedFeatures = new LinkedHashSet<>();
        if (optionalFeatureIds != null) {
            selectedFeatures.addAll(optionalFeatureIds);
        }

        Set<String> artifactIds = new LinkedHashSet<>();
        for (ComposeFeature feature : manifest.features) {
            if (feature.required || selectedFeatures.contains(feature.id)) {
                if (feature.artifacts != null) {
                    artifactIds.addAll(feature.artifacts);
                }
            }
        }

        List<ComposeArtifact> result = new ArrayList<>();
        for (ComposeArtifact artifact : manifest.artifacts) {
            if (artifactIds.contains(artifact.id)) {
                result.add(artifact);
            }
        }
        return result;
    }

    public static File getLibraryClassesJarPath(String artifactId) {
        return new File(new File(LIBRARIES_ROOT, artifactId), "classes.jar");
    }

    public static File getLibraryResourcesPath(String artifactId) {
        return new File(new File(LIBRARIES_ROOT, artifactId), "res");
    }

    public static File getLibraryAssetsPath(String artifactId) {
        return new File(new File(LIBRARIES_ROOT, artifactId), "assets");
    }

    public static File getLibraryProguardConfiguration(String artifactId) {
        return new File(new File(LIBRARIES_ROOT, artifactId), "proguard.txt");
    }

    public static File getLibraryDexFile(String artifactId) {
        return new File(DEX_ROOT, artifactId + ".dex");
    }

    /** Minimal JSON model generated by the Compose packaging workflow. */
    public static final class ComposeManifest {
        public int schemaVersion;
        public String composeVersion;
        public List<ComposeFeature> features = new ArrayList<>();
        public List<ComposeArtifact> artifacts = new ArrayList<>();
    }

    public static final class ComposeFeature {
        public String id;
        public String name;
        public String description;
        public boolean required;
        public String tag;
        public List<String> artifacts = new ArrayList<>();
    }

    public static final class ComposeArtifact {
        public String id;
        public String coordinate;
        public String packageName;
        public List<String> dependencies = new ArrayList<>();
    }

    /**
     * Uses the same asset comparison semantics as the normal built-in asset
     * extraction without coupling Compose storage to BuiltInLibraries.
     */
    private static final class ProjectAssetComparator {
        static boolean hasAssetChanged(String assetPath, File targetFile) throws IOException {
            EncryptedFileUtil fileUtil = new EncryptedFileUtil(false);
            long assetSize = fileUtil.getAssetFileSize(SketchApplication.getAppContext(), assetPath);
            if (!targetFile.exists() || targetFile.length() != assetSize) {
                fileUtil.copyAssetFile(SketchApplication.getAppContext(), assetPath, targetFile.getAbsolutePath());
                return true;
            }
            try (InputStream asset = SketchApplication.getAppContext().getAssets().open(assetPath);
                 InputStream target = new java.io.FileInputStream(targetFile)) {
                byte[] a = readAll(asset);
                byte[] b = readAll(target);
                if (!java.util.Arrays.equals(a, b)) {
                    fileUtil.copyAssetFile(SketchApplication.getAppContext(), assetPath, targetFile.getAbsolutePath());
                    return true;
                }
                return false;
            }
        }

        private static byte[] readAll(InputStream input) throws IOException {
            java.io.ByteArrayOutputStream output = new java.io.ByteArrayOutputStream();
            byte[] buffer = new byte[8192];
            int read;
            while ((read = input.read(buffer)) != -1) {
                output.write(buffer, 0, read);
            }
            return output.toByteArray();
        }
    }
}
